static QImage gradientCircle()
{
	const WhidbeyColors& c = WhidbeyStyle::colors();
	QColor light = c.menuBarFace;
	QColor dark = c.menuExpandDark;
	QImage image(circleSize, circleSize, QImage::Format_ARGB32);
	image.fill(Qt::transparent);
	for (int i = 0; i < circleSize * circleSize; i++) {
		int n = circleMask[i];
		if (n == 0xFF) {
			continue;
		}
		image.setPixel(
			i / circleSize,
			i % circleSize,
			qRgb(
				dark.red() - n * (dark.red() - light.red()) / 0xFF,
				dark.green() - n * (dark.green() - light.green()) / 0xFF,
				dark.blue() - n * (dark.blue() - light.blue()) / 0xFF
			)
		);
	}
	return image;
}

MenuExpandButton::MenuExpandButton(QWidget* parent) : QWidget(parent)
{
	setMouseTracking(true);
	m_hoverTimer.setSingleShot(true);
	m_hoverTimer.setInterval(expandHoverDelay);
	connect(&m_hoverTimer, &QTimer::timeout, this, [this]() {
		if (m_selected) {
			expand();
		}
	});
}

QSize MenuExpandButton::sizeHint() const
{
	return QSize(1, buttonHeight);
}

QWidgetAction* MenuExpandButton::addTo(QMenu* menu)
{
	QWidgetAction* action = new QWidgetAction(menu);
	action->setDefaultWidget(new MenuExpandButton(menu));
	menu->addAction(action);
	return action;
}

void MenuExpandButton::expand()
{
	m_hoverTimer.stop();
	if (onExpand) {
		onExpand();
	}
}

void MenuExpandButton::paintEvent(QPaintEvent* event)
{
	const WhidbeyColors& c = WhidbeyStyle::colors();
	QPainter painter(this);
	if (m_selected) {
		painter.setPen(c.highlightBorder);
		painter.setBrush(c.highlightFace);
		painter.drawRect(rect().adjusted(0, 0, -1, -1));
	}

	int center = width() / 2;
	painter.drawImage(center - 7, 1, gradientCircle());

	painter.setPen(Qt::black);
	for (int offset : {0, 4}) {
		int top = chevronTop + offset;
		painter.drawLine(center - 2, top, center - 1, top + 1);
		painter.drawLine(center, top + 2, center + 2, top);
		painter.drawLine(center - 2, top + 1, center - 1, top + 2);
		painter.drawLine(center, top + 3, center + 2, top + 1);
	}
}

void MenuExpandButton::enterEvent(QEnterEvent* event)
{
	m_selected = true;
	update();
	if (expandOnHover && expandOnHover()) {
		m_hoverTimer.start();
	}
}

void MenuExpandButton::leaveEvent(QEvent* event)
{
	m_selected = false;
	m_hoverTimer.stop();
	update();
}

void MenuExpandButton::mouseReleaseEvent(QMouseEvent* event)
{
	if (event->button() == Qt::LeftButton && rect().contains(event->position().toPoint())) {
		expand();
	}
}
